const $logs = document.getElementById('logs');

export const generateLog = (defender, attacker, count) => {
    const { name: defenderName, damageHP, defaultHP } = defender;
    const { name: attackerName } = attacker;

    const text = logs[random(logs.length) - 1]
        .replace('[ПЕРСОНАЖ №1]', defenderName)
        .replace('[ПЕРСОНАЖ №2]', attackerName);

    return `${text} Втрати: -${count}. Залишилось життів: ${damageHP} / ${defaultHP}`;
};

export const addLog = (text) => {
    const $p = document.createElement('p');
    $p.innerText = text;
    $logs.prepend($p);
};
